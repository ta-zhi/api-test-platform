# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

DATABASES = {
    "default": {
        "ENGINE": "django.db.backends.sqlite3",
        "NAME": BASE_DIR / "db.sqlite3",
        # ------------------------------------------------------------------
        # 下面三个参数是针对压测暴露出来的问题做的调优，逐个说明白：
        #
        # 【问题现象】
        # 100 并发压测时，服务端日志里刷出 101 次
        #     django.db.utils.OperationalError: database is locked
        # 对应 73 个 HTTP 500，失败率 14.7%。
        #
        # 【根因：Django 默认的 DEFERRED 事务会"先读后写"】
        # SQLite 的事务有三种开始方式：
        #     DEFERRED  —— Django 默认。先按【读】事务开始，
        #                   等到第一条写语句时才尝试升级成写锁。
        #     IMMEDIATE —— 一上来就要写锁，拿不到就等（遵守 busy timeout）
        #     EXCLUSIVE —— 排斥所有其他连接
        #
        # 坑就在 DEFERRED 上：如果两个事务都先读了数据、然后都想写，
        # 此时它们的读事务要升级成写事务 —— 这是【无法安全完成】的
        # （互相都在等对方释放读锁），SQLite 判断有死锁风险，
        # 于是【直接返回 SQLITE_BUSY 报错，根本不给你等待重试的机会】。
        # 所以哪怕把 timeout 设得再大，这种场景下也照样报 locked。
        #
        # 改成 IMMEDIATE 后，写锁在事务开始时就去拿，
        # 拿不到就老老实实排队等（此时 timeout 才真正生效），
        # 冲突从"当场报错"变成了"排队等待"。
        # 这是 SQLite + 高并发写入最经典的一个坑。
        #
        # 【WAL 模式：让读和写不再互相堵】
        # SQLite 默认用 rollback journal：写的时候整张库会被锁住，
        # 连读都得排队。WAL（Write-Ahead Logging）改成"写日志、后合并"，
        # 读和写可以同时进行，互不阻塞 —— 对"读多写少"的接口收益极大。
        # synchronous=NORMAL 是配 WAL 的常用组合：
        # 断电时最多丢掉最后一个事务，但写入速度快很多。
        # 对一个测试平台来说，这个取舍是划算的。
        #
        # 【必须承认的局限】
        # WAL 解决了"读写互堵"，但没解决"写与写互斥" ——
        # SQLite 任何时刻仍然只允许【一个】写事务。
        # 所以写操作依然是串行的，这套优化只是把并发能力抬高了一截，
        # 不是彻底解决。真要支撑高并发写入，得换 PostgreSQL。
        # 这一点在性能测试报告里要主动写出来，不能吹成"问题已解决"。
        # ------------------------------------------------------------------
        "OPTIONS": {
            # 等锁最多等 20 秒再报错（默认只有 5 秒，压测时很容易等不到）
            "timeout": 20,
            # 事务一开始就拿写锁，避免 DEFERRED 的升级死锁问题
            "transaction_mode": "IMMEDIATE",
            # 每个新连接建立时执行：开启 WAL、把同步级别降到 NORMAL
            "init_command": "PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL;",
        },
    }
}


