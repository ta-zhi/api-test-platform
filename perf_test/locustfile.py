"""接口性能测试脚本（Locust）。

被测对象：http://127.0.0.1:8000/api/projects/  —— 你自己平台里的「项目管理」接口

【Locust 是什么？】
一个用 Python 写压测脚本的工具。
你写一个"虚拟用户"类，描述这个用户会做哪些事，
Locust 就同时起 N 个这样的虚拟用户去跑，统计吞吐量和响应时间。

它和 pytest 的关系：
    pytest  →  验证接口「对不对」     （功能测试）
    Locust  →  验证接口「快不快」     （性能测试）
    两套东西，打的却是同一个接口。

用法（在 perf_test 目录下）：
    # 带 Web 界面（推荐，能看到实时曲线，可截图）
    ..\\.venv\\Scripts\\python.exe -m locust -f locustfile.py
    # 然后浏览器打开 http://localhost:8089

    # 无界面模式（适合跑固定档位、采集数据）——推荐直接用 run_ladder.py
    ..\\.venv\\Scripts\\python.exe run_ladder.py low
"""

import random

from locust import HttpUser, between, task

# ---------------------------------------------------------------------------
# 【两种数据，两种前缀 —— 这个区分是整个脚本不出假失败的关键】
#
#   perf-seed-*  ：「种子数据」。由 data_prepare.py 预先进库，压测期间【只读不删】。
#                  用来撑起"大数据量"这个条件。
#
#   perf-load-*  ：「过程数据」。压测运行期间由虚拟用户创建，稍后会被自己删掉。
#
# 为什么要分？
#   曾经两个都用同一个前缀，结果 100 并发时冒出 3.4% 的 404 假失败。
#   根因很隐蔽：
#       用户 B 是压测开始 5 秒后才启动的，它启动时去查列表预热，
#       此时用户 A 已经建了一条 id=600。
#       → B 把 600 记进了自己"可读"的池子。
#       后来 A 把 600 删了，B 再拿 600 去查详情 → 404。
#
#   也就是说：**【后启动的用户，会捞到先启动用户建的、稍后会被删的数据】**。
#
#   解决办法：预热时只收 perf-seed-*（永远不会被删），
#             把 perf-load-*（会被删）排除在读池之外。
#             这样"读池里的 id 一定活着"，404 从设计上就不可能发生。
#
#   教训：压测脚本里的"假失败"最危险 —— 它不会让测试崩掉，
#         只会悄悄把错误率抬上去，让你误判成"服务端有问题"。
# ---------------------------------------------------------------------------
LOAD_PREFIX = "perf-load-"

# 清理脚本按这个前缀识别压测数据，两种前缀都以它开头
COMMON_PREFIX = "perf-"

# 预热时一次捞多少条 id 进读池。
#
# 【这个参数是跟着接口优化一起改的】
# 列表接口原来不分页、一次返回全表；优化后默认只返回 100 条，
# 上限 1000 条。所以这里显式要满上限，好让"查详情"任务有足够多的 id 可选。
#
# 顺带说一个容易忽略的点：压测脚本是【依赖于接口契约】的。
# 接口一改（这里是把"全量返回"改成"分页返回"），压测脚本必须跟着改，
# 否则它压的就不是真实的使用方式了 —— 甚至可能因为拿不到足够数据而失真。
# 这也是为什么自动化用例和压测脚本都要跟着被测接口一起维护。
WARMUP_LIMIT = 1000


class ProjectUser(HttpUser):
    """一个虚拟用户：代表一个正在使用「项目管理」接口的真实用户。

    【为什么要设计"权重"而不是只压一个接口？】
    只反复调一个接口，叫单接口基准测试（benchmark），
    它测不出"真实场景下系统能扛多少"。

    真实用户是混合操作的：大部分时间在看（查），偶尔写（增删）。
    所以要把不同操作按【真实发生频率】分配权重，
    这样压出来的数字才有参考价值。
    这就是负载测试（Load Test）和单接口压测的区别。

    【权重怎么定的？】
    4 个任务权重 11 : 5 : 2 : 2（合计 20），换算成百分比：
        查列表 55%  |  查详情 25%  |  新建 10%  |  删除 10%
    读多写少，符合"项目管理"这类系统的真实使用习惯。

    注意这里和最初设想（60/20/15/5）有一点调整：把新建和删除调成 1:1 配平。
    原因是写操作只增不减的话，数据库会随压测时间不断膨胀，
    压测 3 分钟后数据量翻了几倍，第二轮再跑起点就不一样了，结果没法复现。
    压测脚本必须保证【可重复】，所以让增删互相抵消。
    """

    host = "http://127.0.0.1:8000"

    # 【wait_time：用户思考时间】
    # 每个虚拟用户执行完一个任务后，随机等待 1~3 秒再做下一个。
    #
    # 为什么必须有这个？
    #   不加 → 虚拟用户会不间停地"死命发请求"，这是在测【极限承压能力】；
    #   加了 → 模拟真人"看一眼、想一下、再点"的节奏，这是在测【真实负载下的表现】。
    #
    # 面试常问这两个概念：前者叫压力测试（Stress Test），后者叫负载测试（Load Test）。
    wait_time = between(1, 3)

    # ------------------------------------------------------------------
    # on_start：每个虚拟用户【启动时】执行一次
    # ------------------------------------------------------------------
    def on_start(self):
        """预热：把"可以安全读取"的 id 捞进池子。

        【池子设计：只有读池，没有删池 —— 因为删池就是"自己建的"】

        read_ids  —— 只装【永远不会被压测删掉】的数据。
                     预热时从列表里挑，并排除掉 perf-load-* （那是别人建了要删的）。

        own_ids   —— 只装【本虚拟用户自己创建】的数据。删除只从这里取。
                     每个用户一份（实例属性），所以不存在跨用户竞争。

        两条铁律，都是踩坑踩出来的：
          1. 删除范围必须严格限制在"自己造的"，绝不能碰别人的真实数据。
          2. 读池里的 id 必须保证活着，否则就是自己制造假失败。
        """
        self.read_ids: list = []
        self.own_ids: list = []

        with self.client.get(
            f"/api/projects/?limit={WARMUP_LIMIT}",
            name="[预热] GET 列表",
            catch_response=True,
        ) as resp:
            if resp.status_code == 200:
                # 关键过滤：把"压测过程数据"排除在外，它们随时可能被删
                self.read_ids.extend(
                    p["id"] for p in resp.json()
                    if not p["name"].startswith(LOAD_PREFIX)
                )
                resp.success()
            else:
                resp.failure(f"预热失败，状态码 {resp.status_code}")

    # ------------------------------------------------------------------
    # 任务 1：查询项目列表（权重 11 → 55%）
    # ------------------------------------------------------------------
    @task(11)
    def list_projects(self):
        """最常用的操作：看列表 —— 第一页。

        【这是整个压测的重点观察对象，优化前后都盯着它】

        优化前：接口不分页，把整张表一次性返回。
            2 条时   → 十几毫秒
            1 万条时 → 100 毫秒以上，响应体 1.5 MB
            而且成本随数据量【线性增长】，数据越多越慢，永远在恶化。

        优化后：接口默认返回第一页（100 条）。
            单次请求的工作量从"跟表大小相关"变成"跟每页条数相关"，
            是个【常数】。数据涨到 100 万条，只要没人翻到最后一页，
            响应时间基本不变。

        这里刻意压【默认的第一页】，因为那才是绝大多数真实用户的行为 ——
        没人会一上来就翻到第 5000 页。压默认路径，结果才有参考价值。
        """
        self.client.get("/api/projects/")

    # ------------------------------------------------------------------
    # 任务 2：查询单个项目（权重 5 → 25%）
    # ------------------------------------------------------------------
    @task(5)
    def get_project_detail(self):
        """查看某个项目的详情。"""
        if not self.read_ids:
            return  # 池子空就先跳过，别硬发一个必然 404 的请求污染数据

        pid = random.choice(self.read_ids)
        self.client.get(f"/api/projects/{pid}/", name="GET /api/projects/[id]/")

    # ------------------------------------------------------------------
    # 任务 3：新建项目（权重 2 → 10%）
    # ------------------------------------------------------------------
    @task(2)
    def create_project(self):
        """新建一个项目 —— 写操作。

        【写操作是重点怀疑对象】
        因为后端用的是 SQLite，它的写锁是【整个数据库级别】的，
        并发写很容易撞锁。这个任务就是用来把问题压出来的。
        """
        with self.client.post(
            "/api/projects/",
            json={
                "name": f"{LOAD_PREFIX}压测-{random.randint(1, 10**9)}",
                "description": "由 Locust 压测创建",
            },
            name="POST /api/projects/",
            catch_response=True,
        ) as resp:
            if resp.status_code == 201:
                # 只进自己的删池 —— 不进读池，避免别的用户读到后又被自己删掉
                self.own_ids.append(resp.json()["id"])
                resp.success()
            else:
                # 关键：把真实错误原因暴露出来，而不是只看到一个失败计数
                resp.failure(f"{resp.status_code} {resp.text[:200]}")

    # ------------------------------------------------------------------
    # 任务 4：删除项目（权重 2 → 10%）
    # ------------------------------------------------------------------
    @task(2)
    def delete_project(self):
        """删除一个【自己刚建的】项目 —— 也是写操作。

        只从 own_ids 取，也就是"本次压测自己造的、并且是自己这个虚拟用户造的"。
        你原有的真实数据、以及种子数据，都不在任何人的 own_ids 里，
        所以永远不会被删到。
        """
        if not self.own_ids:
            return

        pid = self.own_ids.pop()
        with self.client.delete(
            f"/api/projects/{pid}/", name="DELETE /api/projects/[id]/",
            catch_response=True,
        ) as resp:
            if resp.status_code != 200:
                resp.failure(f"{resp.status_code} {resp.text[:200]}")
